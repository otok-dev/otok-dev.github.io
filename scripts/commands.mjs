// Writes src/content/docs/reference/commands.md from the help of an otok on the PATH (or OTOK=<program>):
// run it after a release whose commands changed, and commit the result.
//   node scripts/commands.mjs
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const otok = process.env.OTOK ?? 'otok';
const run = (...args) => execFileSync(otok, args, { encoding: 'utf8' }).replace(/\r\n/g, '\n').trimEnd();

const version = run('--version').split('\n')[0];
const general = run('help');
const names = [...general.matchAll(/^ {2}([a-z-]+) {2,}/gm)].map((m) => m[1]).filter((n) => n !== 'help');
const maintainers = names.filter((n) => n.startsWith('index-'));
const users = names.filter((n) => !n.startsWith('index-'));

const section = (name) => {
  const help = run('help', name);
  const [usage, , summary, ...more] = help.split('\n');
  const rest = more.join('\n').trim();
  return `## ${name}\n\n${summary}\n\n\`\`\`text\n${usage}${rest ? '\n\n' + rest : ''}\n\`\`\`\n`;
};

const page = `---
title: Commands
description: Every otok command and its options.
sidebar:
  order: 1
---

{/* Generated by scripts/commands.mjs from the help of ${version}; do not edit. */}

Every command takes the global options:

\`\`\`text
${general.slice(general.indexOf('options:'))}
\`\`\`

\`otok help <command>\` prints the same as each section below.

${users.map(section).join('\n')}
# For index maintainers

${maintainers.map(section).join('\n')}`;

writeFileSync(new URL('../src/content/docs/reference/commands.mdx', import.meta.url), page);
console.log(`commands.mdx: ${names.length} commands of ${version}`);
